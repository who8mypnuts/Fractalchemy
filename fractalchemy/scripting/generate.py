"""Flame → Script: a script that rebuilds a flame with the scripting API (a starting point for editing it).

The number formatting and the transform / palette blocks come from `codegen`, shared with the recorder's diff generator.
"""

from __future__ import annotations

from ..fractal.curves import CHANNELS
from ..fractal.scene import Flame
from .codegen import curve_call, num as _num, palette_lines, xform_lines as _xform_lines


def flame_to_script(flame: Flame) -> str:
    """Python that recreates `flame` from scratch (transforms, xaos, palette, colouring, camera)."""
    cam, col = flame.camera, flame.coloring
    lines = [f"# @name Flame: {flame.name}", f"# @description Rebuilds the flame '{flame.name}' from scratch (generated by Flame → Script).", "",
             f"new_flame({flame.name!r}, keep_gradient=False)", f"camera.set_size({cam.width}, {cam.height})",
             f"camera.center = ({_num(cam.center[0])}, {_num(cam.center[1])})",
             f"camera.scale = {_num(cam.scale)}", f"camera.zoom = {_num(cam.zoom)}", f"camera.rotate = {_num(cam.rotate)}"]
    if cam.is_3d():
        import math
        lines.append(f"camera.pitch = {_num(math.degrees(cam.pitch))}; camera.pitch_y = {_num(math.degrees(cam.pitch_y))}; "
                     f"camera.yaw = {_num(math.degrees(cam.yaw))}")
        lines.append(f"camera.perspective = {_num(cam.perspective)}; camera.zpos = {_num(cam.zpos)}; camera.dof = {_num(cam.dof)}")
    lines += [f"flame.oversample = {flame.oversample}", f"flame.filter_radius = {_num(flame.filter_radius)}"]
    lines += ["", f"coloring.brightness = {_num(col.brightness)}", f"coloring.gamma = {_num(col.gamma)}",
              f"coloring.gamma_threshold = {_num(col.gamma_threshold)}", f"coloring.vibrancy = {_num(col.vibrancy)}",
              f"coloring.contrast = {_num(col.contrast)}", f"coloring.background = {tuple(int(c) for c in col.background)}"]
    lines += [curve_call(channel, col.curves.points[channel]) for channel in CHANNELS if not col.curves.is_default(channel)]
    lines.append("")
    for i, x in enumerate(flame.xforms):
        lines.append(f"# transform {i + 1}")
        lines += _xform_lines(x, f"t{i + 1}", final=False)
        lines.append("")
    if flame.final is not None:
        lines.append("# final transform")
        lines += _xform_lines(flame.final, "final", final=True)
        lines.append("")
    if any(x.chaos is not None for x in flame.xforms):
        n = len(flame.xforms)
        lines.append("# xaos: the weights of the transforms following each transform")
        for i, x in enumerate(flame.xforms):
            if x.chaos is not None:
                row = [float(x.chaos[j]) if j < len(x.chaos) else 1.0 for j in range(n)]
                lines.append(f"xaos.set_row({i}, [{', '.join(_num(v) for v in row)}])")
        lines.append("")
    lines.append("# palette (256 colours)")
    lines += palette_lines(flame.palette)
    lines += ["", "print('rebuilt', flame.name, 'with', len(transforms), 'transforms')"]
    return "\n".join(lines) + "\n"


__all__ = ["flame_to_script"]
