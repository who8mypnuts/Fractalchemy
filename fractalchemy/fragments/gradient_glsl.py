"""Gradient → GLSL: a `vec3 gradient(float t)` a fragment can call (Fragmentarium's ggr2glsl, generalised).

Any gradient the host reads (`.ugr`, `.map`, `.flame` palettes, images, the Gradient Library's current
gradient) and GIMP `.ggr` files become one of three GLSL forms:

* **segments** — GIMP's segment arrays and blend maths in GLSL (exact for `.ggr`, including the curved /
  sine / sphere shapes and the HSV colour spaces); host gradients become linear RGB segments;
* **table** — `const vec3` samples with a linear `mix` (cheapest to evaluate, shader-size grows with N);
* **texture** — a 1-D PNG strip and a `uniform sampler2D …; file[…]` line (no shader-size cost).

A *role* optionally wraps the function the way ggr2glsl did: as the object colour (`baseColor` + sliders,
`#define providesColor`) or as the sky (`backgroundColor`, `#define providesBackground`). The maths follow
`formats.ggr.evaluate_segments` exactly so a test can compare the compiled shader with the Python reference.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np

from ..formats.ggr import Segment, sample_segments, segments_from_gradient
from ..model import Gradient

FORMS = ("segments", "table", "texture")
ROLES = ("function", "object", "background")
DEFAULT_TABLE_SIZE = 256


@dataclass(frozen=True)
class GradientGlslOptions:
    """How the gradient is emitted.

    Attributes:
        function_name: The GLSL function (helpers and arrays are prefixed with it).
        form: `segments`, `table` or `texture`.
        table_size: Samples for the table / texture forms.
        role: `function`, `object` (baseColor wrapper) or `background` (backgroundColor wrapper).
        texture_file: The strip's file name as written in the `file[…]` annotation (texture form).
    """
    function_name: str = "gradient"
    form: str = "segments"
    table_size: int = DEFAULT_TABLE_SIZE
    role: str = "function"
    texture_file: str = "gradient.png"


def gradient_to_segments(gradient: Gradient) -> list[Segment]:
    """Linear RGB segments for a host gradient (a thin alias kept for the dialog's imports)."""
    return segments_from_gradient(gradient)


def gradient_glsl(name: str, segments: list[Segment], options: GradientGlslOptions = GradientGlslOptions()) -> str:
    """The complete GLSL snippet for `segments` (the gradient's `name` goes into the header comment)."""
    fn = _identifier(options.function_name)
    header = f"// Gradient \"{name}\" ({len(segments)} segments) — generated by Fractalchemy\n"
    body = {"segments": _segments_form, "table": _table_form, "texture": _texture_form}[options.form]
    return header + body(fn, segments, options) + _role_wrapper(fn, options.role)


def write_strip(segments: list[Segment], path: Path, width: int = DEFAULT_TABLE_SIZE) -> None:
    """Write the gradient as a `width` × 1 RGB PNG (the texture form's `file[…]`)."""
    from PIL import Image

    samples = np.array(sample_segments(segments, width), dtype=np.float64)
    rgb = np.clip(np.rint(samples * 255.0), 0, 255).astype(np.uint8).reshape(1, width, 3)
    Image.fromarray(rgb, "RGB").save(path)


# --- forms -----------------------------------------------------------------
def _segments_form(fn: str, segments: list[Segment], options: GradientGlslOptions) -> str:
    n = len(segments)
    arrays = [
        _array(f"{fn}_left", "float", [_f(s.left) for s in segments]),
        _array(f"{fn}_middle", "float", [_f(s.middle) for s in segments]),
        _array(f"{fn}_right", "float", [_f(s.right) for s in segments]),
        _array(f"{fn}_leftColor", "vec3", [_vec3(s.left_color) for s in segments]),
        _array(f"{fn}_rightColor", "vec3", [_vec3(s.right_color) for s in segments]),
        _array(f"{fn}_blend", "int", [str(int(s.blend)) for s in segments]),
        _array(f"{fn}_space", "int", [str(int(s.color)) for s in segments]),
    ]
    return "".join(arrays) + _HELPERS.replace("G_", f"{fn}_") + _SEGMENT_FUNCTION.replace("G_", f"{fn}_").replace("G(", f"{fn}(").replace("N_", str(n))


def _table_form(fn: str, segments: list[Segment], options: GradientGlslOptions) -> str:
    n = max(2, options.table_size)
    table = _array(f"{fn}_table", "vec3", [_vec3(c) for c in sample_segments(segments, n)])
    return table + _TABLE_FUNCTION.replace("G_", f"{fn}_").replace("G(", f"{fn}(").replace("N_", str(n))


def _texture_form(fn: str, segments: list[Segment], options: GradientGlslOptions) -> str:
    return (f"uniform sampler2D {fn}Tex; file[{options.texture_file}]\n"
            f"#TexParameter {fn}Tex GL_TEXTURE_WRAP_S GL_CLAMP_TO_EDGE\n"
            f"vec3 {fn}(float t) {{ return texture2D({fn}Tex, vec2(clamp(t, 0.0, 1.0), 0.5)).rgb; }}\n")


def _role_wrapper(fn: str, role: str) -> str:
    if role == "object":
        return _OBJECT_ROLE.replace("G(", f"{fn}(")
    if role == "background":
        return _BACKGROUND_ROLE.replace("G(", f"{fn}(")
    return ""


# --- formatting helpers --------------------------------------------------------
def _identifier(name: str) -> str:
    cleaned = "".join(c if c.isalnum() or c == "_" else "_" for c in name.strip()) or "gradient"
    return ("_" + cleaned) if cleaned[0].isdigit() else cleaned


def _f(value: float) -> str:
    return f"{value:.6f}"


def _vec3(color) -> str:
    return "vec3(" + ", ".join(_f(c) for c in color) + ")"


def _array(name: str, glsl_type: str, items: list[str]) -> str:
    n = len(items)
    per_line = 1 if glsl_type == "vec3" else 8
    rows = [", ".join(items[i:i + per_line]) for i in range(0, n, per_line)]
    return f"const {glsl_type} {name}[{n}] = {glsl_type}[{n}](\n    " + ",\n    ".join(rows) + "\n);\n"


_HELPERS = """
float G_linear(float middle, float pos) {
    if (pos <= middle) return middle < 1e-10 ? 0.0 : 0.5 * pos / middle;
    pos -= middle; middle = 1.0 - middle;
    return middle < 1e-10 ? 1.0 : 0.5 + 0.5 * pos / middle;
}
float G_shape(int blend, float middle, float pos) {
    if (blend == 1) {
        if (middle < 1e-10) return 1.0;
        if (1.0 - middle < 1e-10) return 0.0;
        return pos > 0.0 ? pow(pos, log(0.5) / log(middle)) : 0.0;
    }
    if (blend == 5) return pos >= middle ? 1.0 : 0.0;
    float f = G_linear(middle, pos);
    if (blend == 2) return (sin(-1.5707963 + 3.1415927 * f) + 1.0) * 0.5;
    if (blend == 3) { float p = f - 1.0; return sqrt(max(0.0, 1.0 - p * p)); }
    if (blend == 4) return 1.0 - sqrt(max(0.0, 1.0 - f * f));
    return f;
}
vec3 G_rgb2hsv(vec3 c) {
    vec4 K = vec4(0.0, -1.0 / 3.0, 2.0 / 3.0, -1.0);
    vec4 p = mix(vec4(c.bg, K.wz), vec4(c.gb, K.xy), step(c.b, c.g));
    vec4 q = mix(vec4(p.xyw, c.r), vec4(c.r, p.yzx), step(p.x, c.r));
    float d = q.x - min(q.w, q.y);
    return vec3(abs(q.z + (q.w - q.y) / (6.0 * d + 1e-10)), d / (q.x + 1e-10), q.x);
}
vec3 G_hsv2rgb(vec3 c) {
    vec4 K = vec4(1.0, 2.0 / 3.0, 1.0 / 3.0, 3.0);
    vec3 p = abs(fract(c.xxx + K.xyz) * 6.0 - K.www);
    return c.z * mix(K.xxx, clamp(p - K.xxx, 0.0, 1.0), c.y);
}
vec3 G_mixHsv(vec3 a, vec3 b, float f, bool clockwise) {
    vec3 l = G_rgb2hsv(a), r = G_rgb2hsv(b);
    float h;
    if (clockwise) {
        h = l.x - ((r.x <= l.x) ? (l.x - r.x) : (1.0 - (r.x - l.x))) * f;
        if (h < 0.0) h += 1.0;
    } else {
        h = l.x + ((l.x <= r.x) ? (r.x - l.x) : (1.0 - (l.x - r.x))) * f;
        if (h > 1.0) h -= 1.0;
    }
    return G_hsv2rgb(vec3(h, mix(l.yz, r.yz, f)));
}
"""

_SEGMENT_FUNCTION = """vec3 G(float t) {
    t = clamp(t, 0.0, 1.0);
    int first = 0, last = N_ - 1;
    while (first != last) {
        int i = (first + last) / 2;
        if (t <= G_right[i]) last = i; else first = i + 1;
    }
    float span = G_right[first] - G_left[first];
    float middle = 0.5, pos = 0.5;
    if (span >= 1e-10) {
        middle = (G_middle[first] - G_left[first]) / span;
        pos = (clamp(t, G_left[first], G_right[first]) - G_left[first]) / span;
    }
    float f = G_shape(G_blend[first], middle, pos);
    vec3 a = G_leftColor[first], b = G_rightColor[first];
    if (G_space[first] == 0) return mix(a, b, f);
    return G_mixHsv(a, b, f, G_space[first] == 2);
}
"""

_TABLE_FUNCTION = """vec3 G(float t) {
    float x = clamp(t, 0.0, 1.0) * float(N_ - 1);
    int i = int(x);
    return mix(G_table[i], G_table[min(i + 1, N_ - 1)], fract(x));
}
"""

_OBJECT_ROLE = """
// Object colouring from the gradient: place this block BEFORE the raytracer #include.
#define providesColor
#group Gradient colouring
uniform float GradientOffset; slider[-10,0.5,10]
uniform vec3 GradientRotVector; slider[(0,0,0),(1,1,1),(1,1,1)]
uniform float GradientRotAngle; slider[-180,0,180]
uniform float GradientScale; slider[-10,1,10]
vec3 baseColor(vec3 point, vec3 normal) {
    normal *= rotationMatrix3(GradientRotVector, GradientRotAngle);
    normal *= GradientScale;
    return G(clamp((normal.y + GradientOffset) * 0.5, 0.0, 1.0));
}
"""

_BACKGROUND_ROLE = """
// Sky colouring from the gradient: place this block BEFORE the raytracer #include.
#define providesBackground
#group Gradient background
uniform float BackgroundMix; slider[0,0,1]
uniform float BackgroundOffset; slider[-10,0.5,10]
uniform vec3 BackgroundRotVector; slider[(0,0,0),(1,1,1),(1,1,1)]
uniform float BackgroundRotAngle; slider[-180,0,180]
uniform float BackgroundScale; slider[-10,1,10]
vec3 backgroundColor(vec3 dir) {
    dir *= rotationMatrix3(BackgroundRotVector, BackgroundRotAngle);
    vec3 c = G(clamp(dir.y / BackgroundScale + BackgroundOffset, 0.0, 1.0));
    return mix(c, BackgroundColor, BackgroundMix);
}
"""
