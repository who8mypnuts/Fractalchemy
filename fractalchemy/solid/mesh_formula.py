"""`mesh_<name>`: a formula whose points lie on a mesh's surface — the mesh as a table in the parameter texture.

JWildfire's `obj_mesh_wf` / `primitives_wf` idea done with the 3D Editor's assets: the formula is generated as
dialect source (`static const` tables of triangle corners and an area CDF, a fixed-depth binary search, a uniform
barycentric sample) and compiled by the formula compiler like any other, so it runs on both engines and can be
used in any flame — a transform that *is* a smiley face. Meshes larger than `MAX_TRIANGLES` are decimated first.
The formula can be kept: `write_mesh_formula()` saves the source into the user's formulas folder, where the loader
finds it on the next start.
"""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np

from ..formulas import workbench
from ..fractal import variations as V
from .holon import normalized_mesh
from .mesh import Mesh

MAX_TRIANGLES = 1024
SEARCH_STEPS = 11                    # ≥ log2(MAX_TRIANGLES)


def formula_name(asset_name: str) -> str:
    """`mesh_<safe asset name>`."""
    safe = re.sub(r"[^A-Za-z0-9_]+", "_", asset_name).strip("_").lower() or "asset"
    return f"mesh_{safe}"


def mesh_formula_source(mesh: Mesh, name: str, max_triangles: int = MAX_TRIANGLES) -> str:
    """The dialect source of the `mesh_…` formula for `mesh` (centred, unit-sized; decimated to `max_triangles`)."""
    if mesh.face_count == 0:
        raise ValueError("the mesh has no faces")
    if mesh.face_count > max_triangles:
        mesh = mesh.decimated(max_triangles)
    mesh = normalized_mesh(mesh)
    tri = mesh.vertices[mesh.faces].reshape(-1, 9)              # (N, 9): the three corners
    areas = mesh.face_areas()
    total = float(areas.sum()) or 1.0
    cdf = np.cumsum(areas) / total
    cdf[-1] = 1.0
    n = tri.shape[0]
    var = f"{name}_scale"

    def numbers(values) -> str:
        items = [f"{v:.6g}" for v in values]
        return ",\n    ".join(", ".join(items[i:i + 9]) for i in range(0, len(items), 9))

    return f'''/*
    Fractalchemy — generated by the 3D Editor from a mesh asset: points sampled uniformly over the mesh's
    surface ({n} triangles, the mesh centred and scaled to unit size). Weight scales it; {var} too.
*/

typedef struct {{
    double {var};
}} Variables;

#include "apoplugin.h"

APO_PLUGIN("{name}");

APO_VARIABLES(
    VAR_REAL({var}, 1.0)
);

static const double {name}_tri[{n * 9}] = {{
    {numbers(tri.reshape(-1))}
}};

static const double {name}_cdf[{n}] = {{
    {numbers(cdf)}
}};

int PluginVarPrepare(Variation* vp)
{{
    return TRUE;
}}

int PluginVarCalc(Variation* vp)
{{
    double r = random01();
    int lo = 0, hi = {n - 1};
    for (int i = 0; i < {SEARCH_STEPS}; i++) {{
        int mid = (lo + hi) / 2;
        if (lo < hi) {{
            if ({name}_cdf[mid] < r) lo = mid + 1; else hi = mid;
        }}
    }}
    int t = lo * 9;
    double s = sqrt(random01());
    double u = random01();
    double w0 = 1.0 - s, w1 = s * (1.0 - u), w2 = s * u;
    double x = w0 * {name}_tri[t] + w1 * {name}_tri[t + 3] + w2 * {name}_tri[t + 6];
    double y = w0 * {name}_tri[t + 1] + w1 * {name}_tri[t + 4] + w2 * {name}_tri[t + 7];
    double z = w0 * {name}_tri[t + 2] + w1 * {name}_tri[t + 5] + w2 * {name}_tri[t + 8];
    double k = VVAR * VAR({var});
    FPx += k * x;
    FPy += k * y;
    FPz += k * z;
    return TRUE;
}}
'''


def register_mesh_formula(mesh: Mesh, asset_name: str, max_triangles: int = MAX_TRIANGLES) -> V.Variation:
    """Compile and register `mesh_<asset name>` (replacing an earlier one of that name); returns the variation.

    Raises:
        ValueError: For an empty mesh or a compile error.
    """
    name = formula_name(asset_name)
    text = mesh_formula_source(mesh, name, max_triangles)
    try:
        compiled = workbench.compile_formula(text)
    except Exception as exc:  # noqa: BLE001 - the compiler's own error types
        raise ValueError(f"could not compile the mesh formula: {exc}") from exc
    var = compiled.variation
    V.register(var)
    return var


def write_mesh_formula(mesh: Mesh, asset_name: str, folder: Path | None = None, max_triangles: int = MAX_TRIANGLES) -> Path:
    """Save the formula's source as `<name>.c` in the user's formulas folder (or `folder`); returns the path."""
    name = formula_name(asset_name)
    target = (Path(folder) / f"{name}.c") if folder is not None else workbench.user_formula_path(name)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(mesh_formula_source(mesh, name, max_triangles), encoding="utf-8")
    return target


__all__ = ["formula_name", "mesh_formula_source", "register_mesh_formula", "write_mesh_formula", "MAX_TRIANGLES"]
