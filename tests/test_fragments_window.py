def test_preferences_apply_and_persist(window, tmp_path):
    from fractalchemy.fragments.preferences import FragPreferences
    from fractalchemy.ui.fragments.preferences_dialog import PreferencesDialog
    from fractalchemy.ui.fragments.window import load_preferences

    window.open_path(MANDELBULB)
    rendered(window)
    dialog = PreferencesDialog(window, window.prefs)
    dialog.font_size.setValue(13)
    dialog.compat_mode.setCurrentIndex(dialog.compat_mode.findData("patch"))
    dialog.include_list.addItem(str(tmp_path))
    dialog.log_to_file.setChecked(True)
    dialog.log_file.setText(str(tmp_path / "frag.log"))
    dialog.refresh_ms.setValue(80)
    dialog.verbose.setChecked(True)
    prefs = dialog.preferences()
    assert prefs.font_size == 13 and prefs.compat_mode == "patch" and prefs.include_paths == [str(tmp_path)]
    window.apply_preferences(prefs)
    assert window.tabs.document.needs_build                      # a build option changed
    assert window.tabs.editor.font().pointSize() == 13 and window.driver.refresh_ms == 80
    assert window.include_paths() == [tmp_path] and window.build_options().include_paths == [tmp_path]
    window.log.add("info", "mirrored")
    assert "mirrored" in (tmp_path / "frag.log").read_text()
    window.save_state()
    loaded = load_preferences(window._settings)
    assert loaded == prefs.normalised() and loaded.log_to_file
    defaults = FragPreferences.from_dict({"refresh_ms": "9999", "compat_mode": "nonsense", "include_paths": ""})
    assert defaults.refresh_ms == 2000 and defaults.compat_mode == "modernise" and defaults.include_paths == []
    window.build()
    rendered(window, 1)
    assert any(text.startswith("▸ Power") or "Power = " in text for text in window.log.texts())   # verbose: the values after the build


